/* Exports Alter as image files, from the same drawing the site uses.

     node scripts/alter-graphics.mjs

   Writes into docs/alter/graphics/:
     svg/alter-<state>-<light|dark>.svg   one standalone, animated SVG per state and theme
     states.html                          all states on one page, with a theme switch

   Run it again after changing src/lib/alter-svg.js or src/styles/alter-character.css.
   (The PNG files in docs/alter/graphics/png were rendered from these SVGs with a browser.) */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { alterSVG, ALTER_STATES } from "../src/lib/alter-svg.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "docs/alter/graphics");
fs.mkdirSync(path.join(out, "svg"), { recursive: true });

const css = fs.readFileSync(path.join(root, "src/styles/alter-character.css"), "utf8");
// The site switches theme with selectors on <html>; a standalone file gets one fixed theme instead.
const a = css.indexOf("/* Dark values"), b = css.indexOf("/* only the animated parts");
const base = css.slice(0, a) + css.slice(b);
const DARK = ".alter{--alter-a:#3db4e2;--alter-m:#1389b3;--alter-b:#0a9a86;--alter-sa:#0d5f86;--alter-sm:#0a5573;--alter-sb:#06655a;--alter-line:#061f2d;--alter-ring:#e8eef2;--alter-spark:#7fe9dc}";

for (const theme of ["light", "dark"]) {
  for (const state of ALTER_STATES) {
    const svg = alterSVG({ uid: `alter-${state}`, state, label: `Alter (${state})` })
      .replace(/(<svg[^>]*>)/, `$1\n<style>${base}${theme === "dark" ? DARK : ""}</style>`);
    fs.writeFileSync(path.join(out, "svg", `alter-${state}-${theme}.svg`), svg.trim() + "\n");
  }
}

const cells = ALTER_STATES.map((s) => `<figure>${alterSVG({ uid: "s-" + s, state: s, label: "Alter: " + s })}<figcaption>${s}</figcaption></figure>`).join("");
fs.writeFileSync(path.join(out, "states.html"), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Alter: states</title>
<style>
body{margin:0;padding:24px;font:16px/1.5 system-ui,sans-serif;background:#f1f4f7;color:#14212c}
:root[data-theme="dark"] body{background:#0b141c;color:#e8eef2}
h1{font-size:22px;margin:0 0 4px}p{margin:0 0 16px;opacity:.75}
button{font:inherit;padding:8px 14px;border-radius:999px;border:1.5px solid currentColor;background:none;color:inherit;cursor:pointer;margin-bottom:20px}
main{display:grid;grid-template-columns:repeat(auto-fill,minmax(170px,1fr));gap:12px}
figure{margin:0;padding:12px;border-radius:16px;background:#fff;text-align:center}
:root[data-theme="dark"] figure{background:#13212c}
figure svg{width:140px;height:140px;margin:auto}figcaption{font-weight:600;margin-top:4px}
${css}
</style></head><body>
<h1>Alter: the seven states</h1><p>Generated by scripts/alter-graphics.mjs from the drawing the site uses.</p>
<button type="button" onclick="document.documentElement.dataset.theme=document.documentElement.dataset.theme==='dark'?'light':'dark'">Switch theme</button>
<main>${cells}</main>
</body></html>
`);
console.log(`Alter graphics written to ${path.relative(root, out)}: ${ALTER_STATES.length * 2} SVG files and states.html`);
